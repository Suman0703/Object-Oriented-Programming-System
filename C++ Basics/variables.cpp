#include <iostream>
#include <string> // Needed for string type

using namespace std;

int main() {
    // Integer variable
    int age = 20;

    // Floating-point variable
    float weight = 55.5;

    // Character variable
    char grade = 'A';

    // Boolean variable
    bool isStudent = true;

    // String variable
    string name = "Suman";

    // Output all variables
    cout << "Name: " << name << endl;
    cout << "Age: " << age << endl;
    cout << "Weight: " << weight << " kg" << endl;
    cout << "Grade: " << grade << endl;
    cout << "Is Student: " << isStudent << endl; // true will print as 1

    return 0;
}
